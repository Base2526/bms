function imageUrlForProduct(
  root: "catalog" | "starter",
  products: Partial<Record<ShopArchetype, readonly string[]>>,
  archetype: ShopArchetype,
  productName: string
): string | null {
  const index = products[archetype]?.indexOf(productName) ?? -1;
  if (index < 0) return null;
  return `/sample/${root}/${archetype}/${String(index + 1).padStart(2, "0")}.jpg`;
}

export function onboardingSampleImageUrl(archetype: ShopArchetype, productName: string): string | null {
  return imageUrlForProduct("catalog", ONBOARDING_SAMPLE_IMAGE_PRODUCTS, archetype, productName);
}

export function starterSampleImageUrl(archetype: ShopArchetype, productName: string): string | null {
  return imageUrlForProduct("starter", STARTER_SAMPLE_IMAGE_PRODUCTS, archetype, productName);
}
