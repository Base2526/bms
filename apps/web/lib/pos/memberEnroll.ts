/** ช่องว่างและขีดคือการจัดหน้าของคน ไม่ใช่ส่วนของเบอร์ — ตัดออกก่อนตัดสินและก่อนบันทึก */
export function normalizeEnrollPhone(raw: string): string {
  return raw.replace(/[\s-]/g, "").trim();
}

/** เบอร์ที่ `enrollMember()` จะรับ — ตรวจกับค่าที่ normalize แล้วเสมอ ไม่ใช่ค่าดิบ */
export function isEnrollablePhone(raw: string): boolean {
  return /^[0-9+]{8,20}$/.test(normalizeEnrollPhone(raw));
}
