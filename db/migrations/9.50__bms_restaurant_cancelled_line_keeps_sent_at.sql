-- 9.50 — บรรทัดบิลโต๊ะที่ถูกยกเลิกหลังส่งครัว ต้องเก็บ sent_at ไว้ได้
--
-- ที่มา: ครัวกดยกเลิกอาหาร = จานนั้นไม่ได้ทำ บรรทัดต้องหลุดออกจากยอดทันที ไม่ใช่ให้แคชเชียร์
-- เก็บเงินค่าอาหารที่ไม่มีอยู่ (ก่อนหน้านี้ตั๋วหายจากกระดานครัวเงียบ ๆ แต่ยอดยังรวมอยู่)
--
-- ปัญหาที่เจอตอนต่อเส้นทางนั้น: constraint เดิม
--     CHECK ((status = 'SENT') = (sent_at IS NOT NULL))
-- บังคับว่า sent_at มีค่า **เฉพาะ** ตอน status = 'SENT' ดังนั้นการเปลี่ยนบรรทัดที่ส่งครัว
-- ไปแล้วเป็น 'CANCELLED' จะล้มด้วย 23514 ทันที · เดิมไม่เคยชนเพราะทางเดียวที่ยกเลิกได้คือ
-- removeRestaurantCheckItem ซึ่งจำกัด status = 'NEW' (แถวที่ sent_at ยังเป็น NULL อยู่แล้ว)
--
-- **ทางที่ไม่เลือก: ล้าง sent_at ตอนยกเลิก** — ผ่าน constraint เดิมได้โดยไม่ต้องแก้ schema
-- แต่เป็นการลบหลักฐานว่าอาหารจานนั้นถูกส่งเข้าครัวไปแล้วจริงตอนกี่โมง ซึ่งเป็นข้อมูลที่ต้องใช้
-- ตอบว่า "ครัวรับไปแล้วแต่ยกเลิกทีหลัง" ต่างจาก "ยกเลิกก่อนส่ง" — สองกรณีนี้คนละเรื่องกันทั้ง
-- ในการดูแลครัวและการอธิบายลูกค้า
--
-- constraint ใหม่คงการันตีเดิมไว้ทั้งสองข้อ แล้วเปิดช่องเฉพาะสถานะที่ของเดิมไม่ได้คิดถึง:
--   · SENT      ต้องมี sent_at (เหมือนเดิม)
--   · NEW       ต้องไม่มี sent_at (เหมือนเดิม)
--   · CANCELLED มีหรือไม่มีก็ได้ — ไม่มี = ยกเลิกก่อนส่งครัว · มี = ครัวยกเลิกหลังรับไปแล้ว
--
-- ไม่มีการ backfill: แถวที่มีอยู่ทุกแถวผ่าน constraint ใหม่อยู่แล้วโดยนิยาม (เป็น subset)

ALTER TABLE bms_restaurant_check_items
  DROP CONSTRAINT IF EXISTS bms_restaurant_check_items_check1;

ALTER TABLE bms_restaurant_check_items
  ADD CONSTRAINT bms_restaurant_check_items_sent_at_shape CHECK (
    (status = 'SENT' AND sent_at IS NOT NULL)
    OR (status = 'NEW' AND sent_at IS NULL)
    OR status = 'CANCELLED'
  );
