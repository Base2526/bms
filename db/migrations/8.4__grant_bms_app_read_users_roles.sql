-- =============================================================
-- 8.4 — bms_app ต้องอ่าน users/roles ได้ (แก้บั๊กที่ทำให้การคืนยอดสูงล้ม)
-- -------------------------------------------------------------
-- beginTenantTx ทำ `SET LOCAL ROLE bms_app` ทุกครั้ง แปลว่าทุก query ที่อยู่ใน
-- ทรานแซกชันของโมดูล BMS รันในบทบาทนั้น · แต่ bms_app ไม่เคยได้สิทธิ์บน users
-- และ roles เลย ("(none)" ทั้งคู่)
--
-- ผลที่เกิดขึ้นจริง — โค้ดที่ปล่อยไปแล้วตั้งแต่ 7.91:
--   processPosReturn เรียก cashierHasPermissionInTx เมื่อยอดคืนถึงเกณฑ์ที่ต้องมี
--   ผู้อนุมัติ (ตั้งแต่ ฿500) ฟังก์ชันนั้น SELECT จาก users JOIN roles
--   → "permission denied for table users" เป็น error ดิบ ๆ กลางการคืนของ
--   → **การคืนสินค้ายอดตั้งแต่ ฿500 ล้มทุกครั้ง** ส่วนยอดต่ำกว่านั้นผ่าน เพราะ
--     ไม่เข้าเงื่อนไขต้องมีผู้อนุมัติ จึงไม่มีใครเจอตอนทดสอบด้วยบิลเล็ก
--
-- เจอตอนเขียนเทส 8.3 ด้วยบิล ฿2,000 ซึ่งเป็นบิลแรกที่ยอดถึงเกณฑ์
--
-- ให้สิทธิ์ระดับคอลัมน์บน users ไม่ใช่ทั้งตาราง — password_hash ต้องไม่อยู่ใน
-- มือ bms_app ไม่ว่ากรณีใด · การล็อกอินอ่าน password_hash ผ่าน connection ปกติ
-- (ไม่ได้อยู่ใน tenant tx) จึงไม่กระทบ
--
-- roles ให้ทั้งตาราง: เป็นตาราง lookup ที่มีแค่ id/name ไม่มีอะไรอ่อนไหว
-- =============================================================

GRANT SELECT (
  id, tenant_id, role_id, name, email, is_available, created_at
) ON users TO bms_app;

GRANT SELECT ON roles TO bms_app;

COMMENT ON TABLE roles IS
  'role lookup — bms_app อ่านได้ (8.4) เพราะ cashierHasPermissionInTx join ตารางนี้ในทรานแซกชัน';
