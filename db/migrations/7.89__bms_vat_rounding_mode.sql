-- =============================================================
-- 7.89  BMS VAT — วิธีปัดเศษภาษีเป็นค่าตั้งต่อร้าน (แก้ข้อผิดพลาดของ 7.88)
-- -------------------------------------------------------------
-- 7.88 สมมติว่าใบกำกับทุกใบคิด VAT ด้วยวิธีเดียวกัน ซึ่งไม่จริง
-- ตรวจกับเลขบนใบจริงแล้วสองเจ้าใช้คนละวิธี และผลต่างกัน 1 สตางค์:
--
--   วราภรณ์  หาฐานก่อน:  134.00 ÷ 1.07 = 125.2336 → 125.23
--                        VAT = 134.00 − 125.23    = 8.77
--   Makro    หา VAT ก่อน: 354.00 × 7/107 = 23.1588 → 23.15  (ตัดทิ้ง ไม่ปัดขึ้น)
--                        ฐาน = 354.00 − 23.15     = 330.85
--
-- กฎเดียวให้ผลตรงทั้งสองใบไม่มี — เป็นความต่างระหว่างผู้ขายจริง ๆ
-- ทั้งสองแบบยอมรับได้ตราบใดที่เอกสารสอดคล้องกันในตัวเอง
-- ให้ร้านเลือก แล้วห้ามเปลี่ยนหลังออกใบกำกับใบแรกไปแล้ว
--
-- ต้องรัน 7.88 ก่อน · รันซ้ำได้ปลอดภัย
-- =============================================================

ALTER TABLE bms_store_profile
  ADD COLUMN IF NOT EXISTS vat_rounding TEXT NOT NULL DEFAULT 'BASE_FIRST'
    CHECK (vat_rounding IN ('BASE_FIRST', 'VAT_FIRST_TRUNCATE', 'VAT_FIRST_ROUND'));

COMMENT ON COLUMN bms_store_profile.vat_rounding IS
  'BASE_FIRST = ปัดฐานก่อนแล้วลบหา VAT (แบบวราภรณ์) · '
  'VAT_FIRST_TRUNCATE = ตัดเศษ VAT แล้วลบหาฐาน (แบบ Makro) · '
  'VAT_FIRST_ROUND = ปัด VAT ตามปกติแล้วลบหาฐาน';

-- เอกสารที่ออกไปแล้วต้องอ่านย้อนหลังได้เหมือนวันที่พิมพ์ แม้ร้านจะเปลี่ยนค่าตั้ง
ALTER TABLE bms_tax_documents
  ADD COLUMN IF NOT EXISTS vat_rounding TEXT NOT NULL DEFAULT 'BASE_FIRST';
